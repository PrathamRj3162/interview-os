import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { GitBranch, Mic, ShieldQuestion } from "lucide-react";
import { Card, Badge } from "@/components/ui/card";
import { buttonClasses } from "@/components/ui/button";
import { requireUser } from "@/lib/supabase/server";
import { AnalyseButton } from "@/components/learn/projects-ui";
import type { ProjectAnalysis } from "@/lib/projects/analyze";

export const metadata: Metadata = { title: "Project" };

export default async function ProjectPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  if (!/^[0-9a-f-]{36}$/.test(id)) notFound();
  const { supabase } = await requireUser();
  const { data: p } = await supabase.from("projects").select("id, title, description, technologies, repo_url, analysis, repo_snapshot").eq("id", id).maybeSingle();
  if (!p) notFound();
  const a = p.analysis as ProjectAnalysis | null;
  const snap = p.repo_snapshot as { filesRead?: string[]; fullName?: string; fetchedAt?: string } | null;
  return (
    <article className="space-y-5">
      <div>
        <Link href="/projects" className="text-sm text-muted hover:text-text">← Projects</Link>
        <h1 className="mt-1 text-2xl font-semibold tracking-tight">{p.title}</h1>
        {p.repo_url && <a href={p.repo_url} target="_blank" rel="noopener noreferrer" className="mt-1 flex items-center gap-1 text-sm text-muted hover:text-text"><GitBranch className="size-4" aria-hidden />{p.repo_url.replace("https://github.com/", "")}</a>}
      </div>
      <div className="flex flex-wrap gap-2">
        <Link href={`/interview/new?kind=project&persona=skeptic&project=${p.id}`} className={buttonClasses("primary", "sm")}><Mic className="size-4" aria-hidden />Practise a deep dive on this project</Link>
        <AnalyseButton id={p.id} hasRepo={Boolean(p.repo_url)} />
      </div>
      {a ? (
        <>
          <Card data-testid="project-analysis">
            <h2 className="font-medium">What the repository shows</h2>
            <p className="mt-2 text-sm">{a.summary}</p>
            {a.architecture && <p className="mt-2 text-sm text-muted">{a.architecture}</p>}
            <ul className="mt-3 list-disc space-y-1 pl-5 text-sm text-muted">{a.facts.map((f) => <li key={f}>{f}</li>)}</ul>
          </Card>
          <Card>
            <h2 className="font-medium">Questions an interviewer is likely to ask</h2>
            <ol className="mt-3 list-decimal space-y-2 pl-5 text-sm">{a.questions.map((q, i) => <li key={i}>{q.question}{q.probing && <span className="block text-xs text-muted">Probing: {q.probing}</span>}</li>)}</ol>
          </Card>
          {a.verify.length > 0 && (
            <Card>
              <h2 className="flex items-center gap-2 font-medium"><ShieldQuestion className="size-4 text-warning" aria-hidden />Be ready to back these up</h2>
              <ul className="mt-2 list-disc space-y-1 pl-5 text-sm">{a.verify.map((v) => <li key={v}>{v}</li>)}</ul>
            </Card>
          )}
          <p className="text-xs text-muted">
            {a.source === "ai" ? `Generated by ${a.provider} · ${a.model} from the repository data below; AI can be wrong.` : "Generated by rules from the repository data (no AI)."}{" "}
            Read from GitHub{snap?.fetchedAt ? ` on ${new Date(snap.fetchedAt).toLocaleString("en-IN", { dateStyle: "medium", timeStyle: "short" })}` : ""}: repository metadata, file list{snap?.filesRead?.length ? `, ${snap.filesRead.join(", ")}` : ""}. Nothing else.
          </p>
        </>
      ) : (
        <Card className="text-sm text-muted">{p.description ?? "No description."} {p.technologies.length > 0 && <span className="mt-2 flex flex-wrap gap-1">{p.technologies.map((t: string) => <Badge key={t}>{t}</Badge>)}</span>}</Card>
      )}
    </article>
  );
}
